"""
Precision: Precision is the ratio of true positive predictions to the total number of positive predictions made by the model. 
It indicates how many of the predicted positive instances are actually correct.

Recall: Recall, also known as sensitivity or true positive rate, is the ratio of true positive predictions to the total
 number of actual positive instances in the dataset. It measures how well the model identifies all relevant instances.

F1 Score: The F1 score is the harmonic mean of precision and recall. It provides a single metric that balances both precision
 and recall, especially when there is an uneven class distribution. A high F1 score indicates that the model has a good balance 
 between precision and recall.

Support: Support refers to the number of actual occurrences of each class in the dataset. It indicates how many instances belong to 
each class and is used to understand the distribution of classes in the dataset.

Accuracy: Accuracy is the ratio of correctly predicted instances (both true positives and true negatives) to the total number of instances
 in the dataset. It measures the overall correctness of the model's predictions.
"""